#!/usr/bin/env python3
"""Engine/BigramData.h (D30): how often each reading of a tie word (bus/bú, been/bên, mix/mĩ) follows a
word, from real text: Vietnamese web + forums (with the English inside) and English web + Reddit
(vikey-data: bulk/merged/bigram_vi.tsv, bigram_en.tsv, bigram/crawl_vi.tsv; test sets excluded).
Pairs whose second word is a tie form, seen MIN+ times, and pairs whose first word is one, seen NEXT_MIN+ times.
Sorted "prev\\tnext" keys, front-coded in blocks of BLOCK keys: each block starts with a whole key, the others
are (bytes shared with the key before, rest of the key). The engine binary-searches the block heads, then scans."""
import os, sys, unicodedata, collections, math
D = os.path.expanduser('~/Work/vikey-data')
MIN = int(os.environ.get('VIKEY_BIGRAM_MIN', '3'))             # was 10 (exp/bigram-score: more pairs, same size)
NEXT_MIN = int(os.environ.get('VIKEY_BIGRAM_NEXT_MIN', '5'))   # D35: tie word + the word after it (was 20)
BLOCK = 16
T = set()
for l in open(f'{D}/bigram/tie_forms.tsv', encoding='utf-8'):
    a, b = l.rstrip('\n').split('\t'); T.add(a); T.add(unicodedata.normalize('NFC', b))
c = collections.Counter()
for f in ['bulk/merged/bigram_vi.tsv', 'bulk/merged/bigram_en.tsv', 'bigram/crawl_vi.tsv']:
    for l in open(f'{D}/{f}', encoding='utf-8'):
        p = l.rstrip('\n').split('\t')
        if len(p) == 3 and (p[1] in T or p[0] in T): c[(p[0], p[1])] += int(p[2])
keys = sorted((f'{a}\t{b}'.encode('utf-8'), v) for (a, b), v in c.items() if (b in T and v >= MIN) or (a in T and v >= NEXT_MIN))
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'Engine', 'BigramData.h')
data, heads, prev = bytearray(), [], b''
for i, (k, _) in enumerate(keys):
    if i % BLOCK == 0:
        heads.append(len(data)); data += k + b'\0'
    else:
        p = 0
        while p < min(len(k), len(prev), 255) and k[p] == prev[p]: p += 1
        data += bytes([p]) + k[p:] + b'\0'
    prev = k
def esc(b):   # 3-digit octal for anything that isn't plain printable ASCII (and for ? to avoid trigraphs)
    return f'\\{b:03o}' if b >= 0x80 or b < 0x20 or b in (0x22, 0x3f, 0x5c) else chr(b)
with open(out, 'w') as f:
    f.write('// Generated by Tools/autoswitch/build_bigrams.py. Do not edit. Word pairs for ties (D30).\n')
    f.write('// Sources: FineWeb-2 / FineWeb (ODC-By), HPLT 2 (CC0), MADLAD-400 (ODC-By), Reddit, our forum crawl.\n')
    f.write(f'// {len(keys)} pairs, front-coded in blocks of {BLOCK}: a block starts with "prev\\tnext\\0", then each key is\n')
    f.write('// (one byte: bytes shared with the key before) + the rest + \\0.\n')
    f.write('#ifndef BigramData_h\n#define BigramData_h\n')
    f.write('static const char kBigramData[] =\n')
    for i in range(0, len(data), 2000):
        f.write('    "' + ''.join(esc(b) for b in data[i:i + 2000]) + '"\n')
    f.write(';\n')
    f.write(f'static const unsigned int kBigramBlocks[{len(heads)}] = {{' + ','.join(map(str, heads)) + '};\n')
    f.write(f'static const int kBigramBlockCount = {len(heads)};\nstatic const int kBigramBlockSize = {BLOCK};\n')
    # counts as log scale bytes: round(8 * log2(count)), enough precision for a ratio vote
    f.write(f'static const unsigned char kBigramLogCounts[{len(keys)}] = {{' + ','.join(str(min(255, round(8 * math.log2(v)))) for _, v in keys) + '};\n')
    f.write(f'static const int kBigramCount = {len(keys)};\n#endif\n')
print(len(keys), 'pairs,', len(data), 'bytes of keys ->', os.path.normpath(out), os.path.getsize(out), 'bytes')
